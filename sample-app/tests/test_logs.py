"""Tests for demo-shop log buffer and /logs endpoint."""
import time
from fastapi.testclient import TestClient

from app.logs import LogBuffer, log_buffer


def test_log_buffer_add_and_query() -> None:
    """LogBuffer stores entries and returns them in reverse chronological order."""
    buf = LogBuffer(max_size=10)
    buf.add("INFO", "req_1", "/health", 200, 1.2, "v1")
    buf.add("WARN", "req_2", "/products", 404, 2.5, "v1")
    buf.add("ERROR", "req_3", "/checkout", 500, 15.0, "v2", exception="TypeError traceback")

    assert len(buf) == 3
    entries = buf.query()
    assert len(entries) == 3
    # Most recent first
    assert entries[0].request_id == "req_3"
    assert entries[1].request_id == "req_2"
    assert entries[2].request_id == "req_1"


def test_log_buffer_capacity_ring() -> None:
    """Ring buffer drops oldest entries when capacity is exceeded."""
    buf = LogBuffer(max_size=3)
    for i in range(5):
        buf.add("INFO", f"req_{i}", "/products", 200, 1.0, "v1")

    assert len(buf) == 3
    entries = buf.query()
    # Oldest (req_0 and req_1) dropped; remaining: req_4, req_3, req_2
    assert [e.request_id for e in entries] == ["req_4", "req_3", "req_2"]


def test_log_buffer_filter_level() -> None:
    """Filter by log level (case-insensitive)."""
    buf = LogBuffer(max_size=10)
    buf.add("INFO", "req_1", "/health", 200, 1.0, "v1")
    buf.add("ERROR", "req_2", "/checkout", 500, 5.0, "v2")
    buf.add("INFO", "req_3", "/products", 200, 1.5, "v1")

    errors = buf.query(level="ERROR")
    assert len(errors) == 1
    assert errors[0].request_id == "req_2"

    infos = buf.query(level="info")
    assert len(infos) == 2


def test_log_buffer_filter_since() -> None:
    """Filter entries after a timestamp."""
    buf = LogBuffer(max_size=10)
    buf.add("INFO", "req_1", "/health", 200, 1.0, "v1")
    time.sleep(0.01)
    cutoff = buf.query()[0].timestamp
    time.sleep(0.01)
    buf.add("INFO", "req_2", "/products", 200, 1.0, "v1")

    recent = buf.query(since=cutoff)
    assert len(recent) == 2  # includes entry at cutoff and after


def test_logs_endpoint_via_client(client: TestClient) -> None:
    """GET /logs endpoint returns logs generated by requests."""
    # Generate some traffic
    client.get("/products")
    client.get("/health")
    client.get("/products/1")

    response = client.get("/logs?limit=10")
    assert response.status_code == 200
    logs = response.json()
    assert len(logs) >= 3

    # Verify structured fields
    first = logs[0]
    assert "timestamp" in first
    assert "level" in first
    assert "request_id" in first
    assert "route" in first
    assert "status" in first
    assert "latency_ms" in first
    assert "version" in first
